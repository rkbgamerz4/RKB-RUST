//! `rkb-fixture`: write a synthetic Minecraft 1.21 save for verification.
//!
//! The generated save contains no Mojang data. It exists so CI and developers
//! can exercise the real save reader, mesher, and renderer without shipping a
//! world or asking users for files in automated environments.

use std::env;
use std::path::PathBuf;
use std::process::ExitCode;

use rkb_minecraft::demo_world::write_demo_world;

const USAGE: &str = "\
rkb-fixture — write a synthetic Minecraft: Java Edition 1.21 save

Usage:
  rkb-fixture <world-dir>    Create the demo island save in <world-dir>
  rkb-fixture --version      Print the tool version

The save is generated by RKB code. It contains no Minecraft assets and is
intended for tests and emulator verification, not for distribution.
";

fn main() -> ExitCode {
    match run() {
        Ok(code) => code,
        Err(message) => {
            eprintln!("rkb-fixture: {message}");
            ExitCode::from(2)
        }
    }
}

fn run() -> Result<ExitCode, String> {
    let mut args = env::args().skip(1);
    let Some(first) = args.next() else {
        print!("{USAGE}");
        return Ok(ExitCode::SUCCESS);
    };
    if matches!(first.as_str(), "-h" | "--help" | "help") {
        print!("{USAGE}");
        return Ok(ExitCode::SUCCESS);
    }
    if first == "--version" {
        println!("rkb-fixture {}", rkb_minecraft::VERSION);
        return Ok(ExitCode::SUCCESS);
    }
    if args.next().is_some() {
        return Err("expected exactly one output directory".to_owned());
    }
    let dir = PathBuf::from(first);
    let demo = write_demo_world(&dir)?;
    println!("wrote synthetic 1.21 save: {}", dir.display());
    println!(
        "spawn: {}, {}, {}",
        demo.spawn[0], demo.spawn[1], demo.spawn[2]
    );
    println!("chunks: {}", demo.chunks);
    println!("blocks: {}", demo.blocks);
    Ok(ExitCode::SUCCESS)
}
